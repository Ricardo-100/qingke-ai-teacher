// A deterministic two-page PDF used only to verify import, indexing and page isolation.
import { mkdirSync, writeFileSync } from 'node:fs';
const objects = [];
objects.push('<< /Type /Catalog /Pages 2 0 R >>');
objects.push('<< /Type /Pages /Kids [3 0 R 5 0 R] /Count 2 >>');
const page = content => `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 800 500] /Resources << /Font << /F1 7 0 R >> >> /Contents ${content} 0 R >>`;
const stream = s => `<< /Length ${Buffer.byteLength(s)} >>\nstream\n${s}\nendstream`;
objects.push(page(4));
objects.push(stream('0.97 0.97 0.94 rg 0 0 800 500 re f\n0.15 0.25 0.2 rg\nBT /F1 30 Tf 60 415 Td (Rates of change) Tj ET\nBT /F1 22 Tf 60 325 Td (Average rate = delta y / delta x) Tj ET\nBT /F1 18 Tf 60 260 Td (A secant line connects two points.) Tj ET\n0.3 0.5 0.35 RG 3 w 80 120 m 650 235 l S'));
objects.push(page(6));
objects.push(stream('0.97 0.97 0.94 rg 0 0 800 500 re f\n0.15 0.25 0.2 rg\nBT /F1 30 Tf 60 415 Td (The derivative of x squared) Tj ET\nBT /F1 26 Tf 60 320 Td (f\(x\) = x^2) Tj ET\nBT /F1 26 Tf 60 250 Td (derivative = 2x) Tj ET'));
objects.push('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
let pdf = '%PDF-1.4\n'; const offsets = [0];
objects.forEach((obj, i) => { offsets.push(Buffer.byteLength(pdf)); pdf += `${i + 1} 0 obj\n${obj}\nendobj\n`; });
const xref = Buffer.byteLength(pdf);
pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
offsets.slice(1).forEach(offset => { pdf += `${String(offset).padStart(10, '0')} 00000 n \n`; });
pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
mkdirSync('tests/fixtures', { recursive: true });
writeFileSync('tests/fixtures/sample-lesson.pdf', pdf);
