// Isolated local fixture: no real provider, credentials, or existing classroom session is used.
import { chromium } from '@playwright/test';
import http from 'node:http';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
process.env.PORT = '8791';
const { createServer } = await import('../server/index.mjs');
const upstream = http.createServer(async (req, res) => {
  let raw = ''; for await (const chunk of req) raw += chunk;
  const input = JSON.parse(raw);
  const user = input.messages[1].content;
  const source = JSON.parse(typeof user === 'string' ? user : user[0].text);
  await new Promise(resolve => setTimeout(resolve, 1400));
  res.setHeader('Content-Type', 'application/json');
  res.end(JSON.stringify({ choices: [{ message: { content: JSON.stringify({ beats: [{ speech: '这里 R_{ij} 表示矩阵元素。', actions: [{ type: 'circle', targetId: source.targets[0].id }], board: '测试板书' }] }) } }] }));
});
const server = createServer(); let browser;
try {
  await new Promise(resolve => upstream.listen(0, '127.0.0.1', resolve));
  await new Promise(resolve => server.listen(8791, '127.0.0.1', resolve));
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:8791');
  await page.locator('#tts-open').click();
  await page.locator('#tts-dialog[open]').waitFor();
  assert.match(await page.locator('#tts-preview').textContent(), /【英文】R, I, J/);
  await page.locator('#tts-spell').uncheck();
  assert.match(await page.locator('#tts-preview').textContent(), /R.*ij/);
  await page.locator('#tts-spell').check();
  await page.locator('#tts-sample').fill(String.raw`\frac{a}{\sqrt{x^2+1}}`);
  assert.match(await page.locator('#tts-preview').textContent(), /分子是.*【英文】A.*分母是根号/);
  await page.locator('#tts-sample').fill('这里的 R_{ij} 等于 R_ij。x^2 加上 α。');
  await page.locator('#tts-provider').selectOption('api');
  assert.equal(await page.locator('#tts-api-fields').isVisible(), true);
  await page.locator('#tts-provider').selectOption('browser');
  await page.locator('#tts-clean').uncheck();
  assert.match(await page.locator('#tts-preview').textContent(), /R_\{ij\}/);
  await page.locator('#tts-clean').check();
  await page.locator('#tts-save').click();
  await page.locator('#tts-dialog[open]').waitFor({ state: 'hidden' });
  await page.reload();
  await page.locator('#tts-open').click();
  assert.equal(await page.locator('#tts-clean').isChecked(), true);
  assert.equal(await page.locator('#tts-spell').isChecked(), true);
  await mkdir('docs', { recursive: true });
  await page.screenshot({ path: 'docs/speech-settings-preview.png' });
  await page.locator('#tts-close').click();
  await page.locator('#settings-open').click();
  await page.locator('#base-url').fill(`http://127.0.0.1:${upstream.address().port}/v1`);
  await page.locator('#model-name').fill('local-qa-fixture');
  await page.locator('#api-key').fill('local-test-only');
  await page.locator('#save-settings').click();
  await page.locator('#settings-dialog[open]').waitFor({ state: 'hidden' });
  await page.locator('#voice').click();
  await page.locator('#play').click();
  await page.locator('.generation-progress li.current').filter({ hasText: '生成讲解' }).waitFor();
  await page.screenshot({ path: 'docs/generation-progress-preview.png' });
  await page.locator('#play').click();
  assert.equal(await page.locator('.generation-progress').isVisible(), false);
  await page.locator('#play').click();
  await page.locator('.generation-progress.settled').waitFor();
  await page.locator('.message.assistant').waitFor();
  assert.match(await page.locator('.message.assistant').textContent(), /R_\{ij\}/);
  await page.waitForTimeout(750);
  await page.screenshot({ path: 'docs/annotation-preview.png' });
  // Resize the page; the overlay and original page must share the same physical bounds.
  await page.setViewportSize({ width: 1000, height: 900 });
  await page.waitForTimeout(150);
  const image = await page.locator('#slide-image').boundingBox();
  const canvas = await page.locator('#annotation-canvas canvas').first().boundingBox();
  assert.ok(Math.abs(image.width - canvas.width) < 1 && Math.abs(image.height - canvas.height) < 1);
  // A pen stroke should create a smooth, persistent outline and remain undoable.
  await page.locator('[data-tool="pen"]').click();
  const bounds = await page.locator('#annotation-canvas').boundingBox();
  const before = await page.evaluate(() => JSON.parse(localStorage.getItem('qingke-session-v1')).pages[0].ink.length);
  await page.mouse.move(bounds.x + 100, bounds.y + 200); await page.mouse.down();
  await page.mouse.move(bounds.x + 180, bounds.y + 225, { steps: 20 }); await page.mouse.up();
  const after = await page.evaluate(() => JSON.parse(localStorage.getItem('qingke-session-v1')).pages[0].ink.length);
  assert.equal(after, before + 1);
  await page.locator('#undo-ink').click();
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('qingke-session-v1')).pages[0].ink.length), before);
  assert.deepEqual(errors, []);
  console.log('UI checks passed: settings, persistence, real stage events, cancellation/retry, annotations, resize, smooth pen, undo.');
} finally {
  await browser?.close();
  await new Promise(resolve => server.close(resolve));
  await new Promise(resolve => upstream.close(resolve));
}
